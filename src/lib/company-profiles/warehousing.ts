import type {
  CompanyService,
  DivisionProfile,
  ServiceGroup,
  ServiceStatus,
} from "@/lib/division-profiles";

function offer(
  name: string,
  description: string,
  deliverable: string,
  displayOrder: number,
  pricingMethod: string,
  status: ServiceStatus = "active",
): CompanyService {
  return {
    name,
    description,
    deliverable,
    pricingMethod,
    displayOrder,
    includeInPdf: true,
    status,
  };
}

function group(
  name: string,
  displayOrder: number,
  services: CompanyService[],
  note?: string,
): ServiceGroup {
  return { name, displayOrder, services, note };
}

function file<T extends string>(id: string, type: T, title: string, description: string) {
  return { id, type, title, description, dateAdded: "2026-08-26" };
}

